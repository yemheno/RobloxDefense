#!/usr/bin/env python3
"""Generate MeshMap.lua from mesh entries in asset_ids.txt."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSET_IDS = ROOT / "tools" / "asset_ids.txt"
OUT = ROOT / "src" / "shared" / "ReplicatedStorage" / "MeshMap.lua"

PART_ORDER = ["Head", "Torso", "LeftArm", "RightArm", "LeftLeg", "RightLeg", "NPC"]

# Characters with spaces in their names — the FBX export sometimes doubles
# the prefix with underscores: "Hu Tao_Hu_Tao_LeftArm"
SPACE_CHARS = {
    "Hu Tao": "Hu_Tao",
    "Yae Miko": "Yae_Miko",
    "Kujou Sara": "Kujou_Sara",
    "La Signora": "La_Signora",
    "Raiden Shogun": "Raiden_Shogun",
}


def needs_brackets(s: str) -> bool:
    return not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", s)


def parse_meshes() -> dict[str, dict[str, str]]:
    meshes: dict[str, dict[str, str]] = {}
    with open(ASSET_IDS, "r") as f:
        for line in f:
            line = line.strip()
            if not line.startswith("Meshes/"):
                continue
            parts = line.split("\t")
            if len(parts) != 2:
                continue
            name = parts[0].replace("Meshes/", "").strip()
            asset_id = parts[1].strip()

            # Skip duplicate notation like "Aether_Head (1)"
            if "(" in name:
                continue

            # Identify the part suffix
            char_name = None
            part_name = None
            for p in PART_ORDER:
                if name.endswith("_" + p):
                    part_name = p
                    char_name = name[: -(len(p) + 1)]
                    break

            if not part_name:
                print(f"SKIP (no part found): {name}")
                continue

            # Resolve double-prefix names
            for real_name, under_name in SPACE_CHARS.items():
                if char_name == f"{real_name}_{under_name}":
                    char_name = real_name
                    break

            if char_name not in meshes:
                meshes[char_name] = {}
            # Later entries overwrite earlier ones (handles duplicates)
            meshes[char_name][part_name] = asset_id

    return meshes


def generate_lua(meshes: dict[str, dict[str, str]]) -> str:
    lines = [
        "--[[",
        "    MeshMap.lua",
        "    GENERATED by tools/gen_meshmap.py — re-run to refresh from disk.",
        "",
        '    Structure: MeshMap["CharName"] = { PartName = "rbxassetid://...", ... }',
        "    R6 parts: Head, Torso, LeftArm, RightArm, LeftLeg, RightLeg",
        "    NPC parts: NPC (single merged mesh)",
        "--]]",
        "",
        "-- stylua: ignore",
        "return {",
    ]

    for char in sorted(meshes.keys()):
        parts = meshes[char]
        key = f'["{char}"]' if needs_brackets(char) else char

        lines.append("")
        lines.append(f"\t-- {char}")

        sorted_parts = sorted(
            parts.keys(),
            key=lambda p: PART_ORDER.index(p) if p in PART_ORDER else 99,
        )

        inner = ", ".join(
            f'{p} = "rbxassetid://{parts[p]}"' for p in sorted_parts
        )
        lines.append(f"\t{key} = {{ {inner} }},")

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    meshes = parse_meshes()
    lua = generate_lua(meshes)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(lua, encoding="utf-8")
    print(f"Generated {OUT} with {len(meshes)} characters")


if __name__ == "__main__":
    main()
