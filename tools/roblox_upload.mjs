/**
 * roblox_upload.mjs
 *
 * Uploads FBX parts produced by gi_to_roblox.py to Roblox via the Open Cloud
 * Assets API v1, then writes output_ids.json + a Lua CosmeticConfig snippet.
 *
 * Usage:
 *   node roblox_upload.mjs \
 *     --manifest path/to/output/manifest.json \
 *     --creator_id <Roblox userId (number)> \
 *     [--group_id  <groupId if uploading as a group>]
 *
 * API key (§AGX/X49): read from the environment. ROBLOX_OPEN_CLOUD_KEY is
 * preferred (same name as the Python tools); ROBLOX_API_KEY is still
 * accepted. `--api_key` still works but is deprecated: it leaves the key
 * in shell history and the process list, so a warning is printed.
 *
 * Other env vars: ROBLOX_CREATOR_ID, ROBLOX_GROUP_ID
 *
 * Output files (written next to the manifest):
 *   output_ids.json  — { "Head": 12345, "Torso": 67890, ... }
 *   CosmeticConfig_snippet.lua
 *
 * Roblox Open Cloud Assets API reference:
 *   POST https://apis.roblox.com/assets/v1/assets
 *   GET  https://apis.roblox.com/assets/v1/operations/{operationId}
 */

import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve, dirname, join } from "path";
import { fileURLToPath } from "url";
import { createReadStream } from "fs";
import { parseArgs } from "util";
import fetch from "node-fetch";
import FormData from "form-data";

const __dir = dirname(fileURLToPath(import.meta.url));

// ── CLI arguments ────────────────────────────────────────────────────────────
const { values: args } = parseArgs({
  options: {
    manifest:   { type: "string", short: "m" },
    api_key:    { type: "string", short: "k" },
    creator_id: { type: "string", short: "c" },
    group_id:   { type: "string", short: "g" },
    help:       { type: "boolean", short: "h" },
  },
  allowPositionals: false,
});

if (args.help || !args.manifest) {
  console.log(`
Usage: node roblox_upload.mjs --manifest <manifest.json> [options]

Options:
  --manifest,   -m  Path to manifest.json generated by gi_to_roblox.py
  --api_key,    -k  DEPRECATED: leaks the key into shell history / process
                    list. Set ROBLOX_OPEN_CLOUD_KEY (or ROBLOX_API_KEY) instead.
  --creator_id, -c  Roblox user ID as asset owner (or ROBLOX_CREATOR_ID)
  --group_id,   -g  Group ID if uploading as group (or ROBLOX_GROUP_ID)
  --help,       -h  Show this message
`);
  process.exit(0);
}

// §AGX/X49: env first; the CLI flag is a deprecated fallback. Never print
// the key itself (only which source it came from).
const ENV_API_KEY = process.env.ROBLOX_OPEN_CLOUD_KEY || process.env.ROBLOX_API_KEY;
if (args.api_key) {
  console.warn(
    "WARNING: --api_key is deprecated: the key is now in your shell history " +
    "and visible in the process list. Set ROBLOX_OPEN_CLOUD_KEY in the " +
    "environment instead (and consider rotating this key)." +
    (ENV_API_KEY ? " Using the --api_key value over the environment." : "")
  );
}
const API_KEY    = args.api_key    || ENV_API_KEY;
const CREATOR_ID = args.creator_id || process.env.ROBLOX_CREATOR_ID;
const GROUP_ID   = args.group_id   || process.env.ROBLOX_GROUP_ID;

if (!API_KEY)    { console.error("ERROR: set ROBLOX_OPEN_CLOUD_KEY (or ROBLOX_API_KEY) in the environment"); process.exit(1); }
if (!CREATOR_ID && !GROUP_ID) { console.error("ERROR: --creator_id or --group_id required"); process.exit(1); }

const ASSETS_ENDPOINT    = "https://apis.roblox.com/assets/v1/assets";
const OPERATIONS_ENDPOINT = "https://apis.roblox.com/assets/v1/operations";
const POLL_INTERVAL_MS   = 3_000;
const POLL_MAX_ATTEMPTS  = 40;   // 2 minutes max wait per part

// ── Load manifest ────────────────────────────────────────────────────────────
const manifestPath = resolve(args.manifest);
if (!existsSync(manifestPath)) {
  console.error(`ERROR: manifest not found at ${manifestPath}`);
  process.exit(1);
}

const manifest  = JSON.parse(readFileSync(manifestPath, "utf-8"));
const outDir    = dirname(manifestPath);
const charName  = manifest.character ?? "Unknown";
const mode      = manifest.mode ?? "npc";

console.log(`\n[roblox_upload] Character : ${charName}`);
console.log(`[roblox_upload] Mode      : ${mode}`);
console.log(`[roblox_upload] Parts     : ${Object.keys(manifest.parts).join(", ")}\n`);

// ── Creator context ───────────────────────────────────────────────────────────
function buildCreator() {
  if (GROUP_ID) return { groupId: String(GROUP_ID) };
  return { userId: String(CREATOR_ID) };
}

// ── Upload one FBX → returns assetId (number) ────────────────────────────────
async function uploadFbx(partName, fbxPath, displayName) {
  if (!existsSync(fbxPath)) throw new Error(`FBX not found: ${fbxPath}`);

  const form = new FormData();
  form.append("request", JSON.stringify({
    assetType: "Model",
    displayName,
    description: `${charName} ${partName} — exported by gi_to_roblox`,
    creationContext: { creator: buildCreator() },
  }), { contentType: "application/json" });
  form.append("fileContent", createReadStream(fbxPath), {
    filename:    `${partName}.fbx`,
    contentType: "model/fbx",
  });

  const res = await fetch(ASSETS_ENDPOINT, {
    method:  "POST",
    headers: { "x-api-key": API_KEY, ...form.getHeaders() },
    body:    form,
  });

  const body = await res.json().catch(() => ({}));
  if (!res.ok) {
    throw new Error(`Upload failed (${res.status}): ${JSON.stringify(body)}`);
  }

  // Response: { "path": "operations/{id}", ... }
  const operationId = (body.path ?? "").replace(/^operations\//, "");
  if (!operationId) throw new Error(`No operation ID in response: ${JSON.stringify(body)}`);

  return pollOperation(operationId, partName);
}

// ── Poll operation until done ─────────────────────────────────────────────────
async function pollOperation(operationId, label) {
  for (let i = 0; i < POLL_MAX_ATTEMPTS; i++) {
    await sleep(POLL_INTERVAL_MS);

    const res  = await fetch(`${OPERATIONS_ENDPOINT}/${operationId}`, {
      headers: { "x-api-key": API_KEY },
    });
    const body = await res.json().catch(() => ({}));

    if (!res.ok) {
      throw new Error(`Poll failed (${res.status}): ${JSON.stringify(body)}`);
    }

    if (body.done) {
      if (body.error) throw new Error(`Operation error: ${JSON.stringify(body.error)}`);
      const assetId = body.response?.assetId;
      if (!assetId) throw new Error(`No assetId in response: ${JSON.stringify(body)}`);
      console.log(`[roblox_upload]   ${label} → rbxassetid://${assetId}`);
      return Number(assetId);
    }

    process.stdout.write(`[roblox_upload]   ${label} (attempt ${i + 1}/${POLL_MAX_ATTEMPTS}) …\r`);
  }
  throw new Error(`Timed out waiting for ${label} (operationId=${operationId})`);
}

function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }

// ── Main ──────────────────────────────────────────────────────────────────────
const outputIds = {};
const errors    = [];

for (const [partName, partInfo] of Object.entries(manifest.parts)) {
  const fbxPath    = join(outDir, partInfo.file);
  const displayName = `${charName}_${partName}`;
  console.log(`[roblox_upload] Uploading ${displayName} …`);

  try {
    outputIds[partName] = await uploadFbx(partName, fbxPath, displayName);
  } catch (err) {
    console.error(`[roblox_upload] ERROR on ${partName}: ${err.message}`);
    errors.push({ partName, error: err.message });
  }
}

// ── Write output_ids.json ────────────────────────────────────────────────────
const idsPath = join(outDir, "output_ids.json");
writeFileSync(idsPath, JSON.stringify({ character: charName, mode, assetIds: outputIds }, null, 2));
console.log(`\n[roblox_upload] output_ids.json → ${idsPath}`);

// ── Generate Lua CosmeticConfig snippet ──────────────────────────────────────
const luaLines = [
  `-- CosmeticConfig entry for ${charName} (${mode} mode)`,
  `-- Generated by roblox_upload.mjs — paste into CosmeticConfig.lua`,
  ``,
  `["${charName}"] = {`,
];

if (mode === "npc" && outputIds.NPC) {
  luaLines.push(`    MeshId = "rbxassetid://${outputIds.NPC}",`);
} else {
  for (const [part, id] of Object.entries(outputIds)) {
    luaLines.push(`    ${part} = "rbxassetid://${id}",`);
  }
}
luaLines.push(`},`, ``);

const luaSnippet = luaLines.join("\n");
const luaPath    = join(outDir, "CosmeticConfig_snippet.lua");
writeFileSync(luaPath, luaSnippet);
console.log(`[roblox_upload] Lua snippet  → ${luaPath}`);

// ── Summary ───────────────────────────────────────────────────────────────────
const successCount = Object.keys(outputIds).length;
const totalCount   = Object.keys(manifest.parts).length;
console.log(`\n[roblox_upload] ✓ ${successCount}/${totalCount} parts uploaded successfully.`);
if (errors.length) {
  console.error(`[roblox_upload] ${errors.length} error(s):`);
  errors.forEach(e => console.error(`  - ${e.partName}: ${e.error}`));
  process.exit(1);
}
